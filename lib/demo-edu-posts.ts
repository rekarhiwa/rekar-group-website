function toHtml(def: EduDef): string {
  const items = def.bullets.map((bullet) => `<li>${bullet}</li>`).join("\n");
  return `<h2>${def.introTitle}</h2>
<p>${def.intro}</p>
<h2>${def.listTitle}</h2>
<ul>
${items}
</ul>
<p>${def.outro}</p>`;
}

export function createDemoEduPosts(
  categories: PostCategory[],
  tags: Tag[]
): Post[] {
  const bySlug = Object.fromEntries(categories.map((item) => [item.slug, item]));
  const tagBySlug = Object.fromEntries(tags.map((item) => [item.slug, item]));

  const base = {
    author_id: null,
    status: "published" as const,
    deleted_at: null,
  };

  return EDU_DEFS.map((def, index) => {
    const primary = bySlug[def.cats[0]] ?? bySlug.tips;
    const cover = `/posts/${def.slug}.png`;
    const minute = 20 * 60 - index * 8;
    const hour = Math.floor(minute / 60);
    const mins = minute % 60;
    const stamp = `2026-09-12T${String(hour).padStart(2, "0")}:${String(mins).padStart(2, "0")}:00Z`;
    const postTags = ["edu", ...def.tagSlugs]
      .map((slug) => tagBySlug[slug])
      .filter((item): item is Tag => Boolean(item));
    const uniqueTags = [...new Map(postTags.map((item) => [item.id, item])).values()];

    return post({
      ...base,
      id: `po${60 + index}`,
      title: def.title,
      slug: def.slug,
      excerpt: def.excerpt,
      content: toHtml(def),
      cover_image: cover,
      category_id: primary.id,
      featured: Boolean(def.featured),
      published_at: stamp,
      seo_title: def.seoTitle,
      seo_description: def.seoDescription,
      og_image: cover,
      created_at: stamp,
      updated_at: stamp,
      category: primary,
      tags: uniqueTags,
    });
  });
}
